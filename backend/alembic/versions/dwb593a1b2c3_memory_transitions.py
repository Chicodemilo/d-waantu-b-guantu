"""memory transitions: adopting/reverting states + per-entry pipeline (DWB-593)

Revision ID: dwb593a1b2c3
Revises: dwb584a1b2c3
Create Date: 2026-09-30 00:00:00.000000

Hand-written. Autogenerate does not detect ENUM widenings AT ALL, so an
autogenerated diff for this migration would be silently empty for half of it.

WHAT BUG THIS FIXES, AND THE FRAMING MATTERS MORE THAN THE CODE. Flipping
`memory_mode` straight to `human_memory` sealed the flat file (DWB-589) against
an empty store, so every agent on that project spawned amnesiac until someone
flipped it back.

THE SEAL IS NOT THE DEFECT AND IS NOT TOUCHED BY THIS MIGRATION. It does
exactly what DWB-589 specified, instantly and completely, which was right for a
flag nobody could flip without a migration behind it. What was missing is that
nothing enforced that precondition. So the fix is to make the state the seal
fires in UNREACHABLE, not to give the seal exceptions. A seal with exceptions
leaks on a path nobody tested, and hard rule 1 exists to stop two memories both
looking authoritative.

THE NO-OUTAGE PROPERTY COMES FREE, AND IT IS WORTH KNOWING WHY. There is
exactly one `memory_mode` predicate in the backend, at
`app/services/memory_mode.py`, and it reads `== MemoryMode.human_memory` rather
than `!= MemoryMode.stock`. So a project in `adopting` or `reverting` is simply
not sealed: stock stays authoritative for reads and writes throughout, and an
agent spawning mid-transition notices nothing. Anyone "tidying" that predicate
to `!= stock` re-creates the original outage on a new path; a test asserts it.
"""

